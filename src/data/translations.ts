export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let str = STR[lang]?.[key] ?? STR.fr[key] ?? key;
  if (params) {
    for (const p in params) {
      str = str.replaceAll(`{${p}}`, String(params[p]));
    }
  }
  return str;
}

